// Helper lookups
export const exerciseMap = new Map<string, ExerciseDefinition>(
  exercises.map((e) => [e.id, e])
);

export function getExerciseById(id: string): ExerciseDefinition | undefined {
  return exerciseMap.get(id);
}

export function getExercisesByCategory(category: string): ExerciseDefinition[] {
  return exercises.filter((e) => e.category === category);
}

export function getExercisesByEquipment(equipmentCodes: string[]): ExerciseDefinition[] {
  const codeSet = new Set(equipmentCodes);
  return exercises.filter((e) =>
    e.equipmentCodes.some((code) => codeSet.has(code))
  );
}

export function getExercisesByMuscle(muscle: string): ExerciseDefinition[] {
  return exercises.filter(
    (e) =>
      e.primaryMuscles.includes(muscle) ||
      e.secondaryMuscles.includes(muscle)
  );
}

export function searchExercises(query: string): ExerciseDefinition[] {
  const q = query.toLowerCase();
  return exercises.filter(
    (e) =>
      e.name.toLowerCase().includes(q) ||
      e.aliases.some((a) => a.toLowerCase().includes(q)) ||
      e.category.toLowerCase().includes(q) ||
      e.primaryMuscles.some((m) => m.toLowerCase().includes(q))
  );
}

